"""Writes THIRD-PARTY-NOTICES.txt: the licence of every crate built into bootmend.exe.

Run it from the repository root after changing dependencies:

    python tools/third_party_notices.py

It reads `cargo metadata`, follows the normal (not build or dev) dependencies from Bootmend
for the Windows x64 target, and copies each crate's own licence files from Cargo's cache.
Some crates publish no licence file; their repository's files are kept in tools/licences,
in a folder named after the GitHub owner and repository.
"""

import json
import pathlib
import re
import subprocess
import sys

OUT = pathlib.Path("THIRD-PARTY-NOTICES.txt")
UPSTREAM = pathlib.Path(__file__).parent / "licences"
NAMES = re.compile(r"^(licen[cs]e|copying|notice|ofl|ufl|unlicense)", re.I)
# Folders whose every text file is a licence: REUSE's LICENSES, and egui's bundled fonts.
LICENCE_DIRS = {"licenses", "fonts"}
RULE = "=" * 78


def licence_files(pkg_dir: pathlib.Path) -> list[pathlib.Path]:
    """Licence files at the crate's root, or one folder down."""
    found = [p for p in pkg_dir.iterdir() if p.is_file() and NAMES.match(p.name)]
    for sub in pkg_dir.iterdir():
        if sub.is_dir() and sub.name.lower() in LICENCE_DIRS:
            found += [p for p in sub.iterdir() if p.is_file() and p.suffix.lower() == ".txt"]
        elif sub.is_dir() and sub.name not in ("src", "tests", "benches", "examples", "target"):
            found += [p for p in sub.iterdir() if p.is_file() and NAMES.match(p.name)]
    return sorted(found, key=lambda p: str(p.relative_to(pkg_dir)).lower())


def upstream_files(repository: str) -> list[pathlib.Path]:
    m = re.match(r"https://github\.com/([^/]+)/([^/]+)", repository or "")
    folder = UPSTREAM / f"{m[1]}-{m[2]}" if m else None
    return sorted(folder.iterdir()) if folder and folder.is_dir() else []


def main() -> int:
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-pc-windows-msvc"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            check=True,
        ).stdout
    )
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    shipped, todo = set(), [root]
    while todo:
        for dep in nodes[todo.pop()]["deps"]:
            normal = any(k["kind"] is None for k in dep["dep_kinds"])
            if normal and dep["pkg"] not in shipped:
                shipped.add(dep["pkg"])
                todo.append(dep["pkg"])

    crates = sorted((packages[i] for i in shipped), key=lambda p: (p["name"], p["version"]))
    printed: dict[str, str] = {}
    missing = []
    out = [
        "Third-party notices for Bootmend",
        "",
        "Bootmend is built from the open-source Rust crates below. Each is listed with its",
        "licence and the licence files it ships with. A text that appeared earlier is named",
        "rather than repeated. Generated by tools/third_party_notices.py.",
        "",
    ]
    for p in crates:
        out += [RULE, f"{p['name']} {p['version']}", f"Licence: {p.get('license') or 'see the files below'}"]
        if p.get("authors"):
            out.append(f"Authors: {', '.join(p['authors'])}")
        if p.get("repository"):
            out.append(f"Source: {p['repository']}")
        name = f"{p['name']} {p['version']}"
        pkg_dir = pathlib.Path(p["manifest_path"]).parent
        files = licence_files(pkg_dir)
        # A crate with licence files only in a subfolder (egui's fonts) may still lack its own.
        if not any(f.parent == pkg_dir for f in files):
            upstream = upstream_files(p.get("repository"))
            if upstream:
                out += ["", "The published crate has no licence file of its own, so the repository's are included."]
                files += upstream
            elif not files:
                missing.append(name)
                out += ["", "The published crate has no licence file; its licence is named above."]
        for f in files:
            text = f.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()
            key = " ".join(text.split())
            out += ["", f"--- {f.name} ---", ""]
            if key in printed:
                out.append(f"(The same text as {printed[key]} above.)")
            else:
                printed[key] = f"{f.name} for {name}"
                out.append(text)
        out.append("")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(crates)} crates, {len(printed)} distinct texts, {len(missing)} without a licence file")
    for m in missing:
        print(f"  no licence file: {m}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
